import { useState, useEffect } from 'react';
import './splash.css';

const SplashScreen = () => {
  const [isAnimating, setIsAnimating] = useState(true);
  const [showLogin, setShowLogin] = useState(false);

  useEffect(() => {
    const fillTimer = setTimeout(() => {
      setIsAnimating(false);
    }, 2000);

    const loginTimer = setTimeout(() => {
      setShowLogin(true);
    }, 3500);

    return () => {
      clearTimeout(fillTimer);
      clearTimeout(loginTimer);
    };
  }, []);

  if (showLogin) {
    return <LoginPage />;
  }

  return (
    <div className="splash-container">
      <div className={`splash-bg ${isAnimating ? '' : 'splash-bg-expand'}`}>
        <div className="splash-gradient-1"></div>
        <div className="splash-gradient-2"></div>
      </div>

      <div className={`splash-content ${isAnimating ? '' : 'splash-content-fade'}`}>
        <div className="splash-center">
          <h1 className="splash-title">Veridian</h1>
          <div className="splash-dots">
            <div className="splash-dot"></div>
            <div className="splash-dot" style={{ animationDelay: '0.2s' }}></div>
            <div className="splash-dot" style={{ animationDelay: '0.4s' }}></div>
          </div>
        </div>
      </div>
    </div>
  );
};

