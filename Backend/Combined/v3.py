def NewsAnalysis(result):

    import os, math, time, re
    import numpy as np
    import torch
    import feedparser
    from transformers import AutoTokenizer, AutoModelForSequenceClassification
    from newspaper import Article
    from urllib.parse import quote_plus
    from bs4 import BeautifulSoup
    from typing import List, Dict
    import spacy

    result = result.replace(".NS","").replace(".BO","")

    # ================= CONFIG =================
    DRIVE_MODEL_PATH = "/content/drive/MyDrive/Veridian/finbert_financial_mixed"


    SOURCE_WEIGHTS = {
        "twitter": 0.6,
        "google_news": 1.0,
        "economic_times": 1.0,
        "cnbc": 1.1,
        "investing_com": 0.9,
        "yahoo_finance": 1.0,
        "reuters": 1.1,
        "bloomberg": 1.2,
        "default": 1.0
    }

    RECENCY_LAMBDA = 0.02
    MAX_NEWS = 5
    MAX_TWEETS = 50

    # ================= NLP =================
    try:
        nlp = spacy.load("en_core_web_sm")
    except:
        nlp = None

    # ================= LOAD MODEL =================
    try:
        tokenizer = AutoTokenizer.from_pretrained(DRIVE_MODEL_PATH)
        model = AutoModelForSequenceClassification.from_pretrained(DRIVE_MODEL_PATH)
        model.eval()
        if torch.cuda.is_available():
            model.to("cuda")
    except:
        return {
            "prediction":[0.33,0.33,0.34],
            "confidence":0.0,
            "reason":"Sentiment model not loaded"
        }

    # ================= CLEAN =================
    def clean_text(text):
        if not text or len(text)<50: return text
        footers=["read more","copyright","privacy policy","subscribe now","click here"]
        for f in footers:
            if f in text.lower():
                text=text[:text.lower().find(f)]
        return text.strip()

    # ================= SCRAPE NEWS =================
    def scrape_news(query):
        items=[]
        term=quote_plus(query)
        sources=[
            ("google_news",f"https://news.google.com/rss/search?q={term}&hl=en-US&gl=US&ceid=US:en",1.0),
            ("economic_times","https://economictimes.indiatimes.com/markets/stocks/rssfeeds/2146842.cms",1.0),
            ("cnbc","https://search.cnbc.com/rs/search/combinedcms/view.xml?partnerId=wrss01&id=10000664",1.1),
            ("investing_com","https://www.investing.com/rss/stock_Market.rss",0.9),
            ("yahoo_finance","https://finance.yahoo.com/news/rssindex",0.9)
        ]

        for name,url,w in sources:
            feed=feedparser.parse(url)
            for e in feed.entries:
                if len(items)>=MAX_NEWS: break
                title=e.get("title","")
                summary=e.get("summary","")
                link=e.get("link","")

                if summary:
                    summary=BeautifulSoup(summary,"html.parser").get_text()

                combined=(title+" "+summary).lower()
                if result.lower().split()[0] not in combined:
                    continue

                text=f"{title}\n\n{summary}"

                if link and len(text)<200:
                    try:
                        art=Article(link)
                        art.download(); art.parse()
                        if len(art.text)>200:
                            text=f"{art.title}\n\n{art.text}"
                    except: pass

                text=clean_text(text)

                if len(text)>60:
                    items.append({
                        "text":text,
                        "source":name,
                        "source_weight":w,
                        "timestamp":time.time()
                    })
        return items

    # ================= SCRAPE TWEETS =================
    def scrape_tweets(query):
        try:
            import snscrape.modules.twitter as sntwitter
        except:
            return []
        items=[]
        q=f"{query} since:2024-11-01"
        for i,t in enumerate(sntwitter.TwitterSearchScraper(q).get_items()):
            if i>=MAX_TWEETS: break
            items.append({
                "text":t.rawContent,
                "source":"twitter",
                "source_weight":SOURCE_WEIGHTS["twitter"],
                "timestamp":t.date.timestamp()
            })
        return items

    # ================= SENTIMENT =================
    def predict_sentiment(text, entity=None):

      if entity:
          inputs = tokenizer(text, text_pair=entity,
                            return_tensors="pt",
                            truncation=True, padding=True, max_length=128)
      else:
          inputs = tokenizer(text,
                            return_tensors="pt",
                            truncation=True, padding=True, max_length=128)

      if torch.cuda.is_available():
          inputs = {k:v.to("cuda") for k,v in inputs.items()}

      with torch.no_grad():
          out = model(**inputs)

      logits = out.logits.cpu().numpy()[0]

      import torch.nn.functional as F
      probs = F.softmax(torch.tensor(logits), dim=-1).numpy()

      label_map = model.config.id2label

      p_raw = {label_map[i].lower(): probs[i] for i in range(len(probs))}

      positive = p_raw.get("positive", 0)
      negative = p_raw.get("negative", 0)

      neutral = max(0, 1 - abs(positive - negative))

      total = positive + negative + neutral

      p = {
          "positive": positive/total,
          "negative": negative/total,
          "neutral": neutral/total
      }

      sentiment_value = p["positive"] - p["negative"]
      confidence = max(p.values())

      return p, sentiment_value, confidence


    # ================= RECENCY =================
    def recency(ts):
        return math.exp(-RECENCY_LAMBDA*((time.time()-ts)/3600))

    # ================= EVENT =================
    def extract_event(text):
        if not text: return "No information available"
        patterns=[r'earnings',r'acquire',r'merger',r'strike',r'bankruptcy',
                  r'launch',r'recall',r'surge',r'plunge']
        for p in patterns:
            m=re.search(p,text,re.I)
            if m:
                s=max(0,m.start()-40); e=min(len(text),m.end()+60)
                return text[s:e]
        if nlp:
            doc=nlp(text[:400])
            for s in doc.sents:
                if len(s.text)>20:
                    return s.text[:120]
        return text[:120]

    # ================= AGGREGATE =================
    def aggregate(items):
        ap=an=ag=den=0
        confs=[]; srcs=[]
        best=None; best_score=-1

        for it in items:
            w=recency(it["timestamp"])*it["source_weight"]
            probs,sv,conf=predict_sentiment(it["text"],result)

            ap+=w*probs["positive"]
            an+=w*probs["negative"]
            ag+=w*probs["neutral"]
            den+=w

            confs.append(conf)
            srcs.append(it["source_weight"])

            if w*conf>best_score:
                best_score=w*conf
                best=it["text"]

        if den>0:
            ap/=den; an/=den; ag/=den
        else:
            ap=an=ag=1/3

        prediction=[float(ap),float(an),float(ag)]

        c_model=np.mean(confs) if confs else 0
        c_source=np.mean(srcs)/max(SOURCE_WEIGHTS.values()) if srcs else 0
        c_volume=min(1,math.log(1+len(items))/math.log(101))

        confidence=0.65*c_model+0.25*c_source+0.10*c_volume

        return {
            "prediction":prediction,
            "confidence":round(float(confidence),4),
            "reason":extract_event(best) if best else "No data"
        }

    # ================= RUN =================
    news=scrape_news(f"{result} stock")
    tweets=scrape_tweets(result)
    items=news+tweets

    return aggregate(items)

