    # Check 1: Try the raw ticker (e.g., "TSLA")
    print(f"🔍 Checking ticker: {candidate}...")
    try:
        t = yf.Ticker(candidate)
        hist = t.history(period="5d")
        if len(hist) > 0:
            print(f"✔ Validated: {candidate}")
            return candidate
    except:
        pass

    # Check 2: Try adding .NS for Indian Markets (e.g., "PNB" -> "PNB.NS")
    # (Only if it doesn't already end with .NS or .BO)
    if not (candidate.endswith(".NS") or candidate.endswith(".BO")):
        candidate_ns = candidate + ".NS"
        print(f"🔍 Ticker '{candidate}' failed. Trying: {candidate_ns}...")
        try:
            t = yf.Ticker(candidate_ns)
            hist = t.history(period="5d")
            if len(hist) > 0:
                print(f"✔ Validated: {candidate_ns}")
                return candidate_ns
        except:
            pass

    # Check 3: Fallback (Return original if nothing works, let individual models handle errors)
    print(f"⚠ Could not validate '{candidate}'. Using as-is.")
    return candidate

