def Analyst_Consensus_Direct(ticker):
    import yfinance as yf
    import pandas as pd

    print(f"📊 Fetching Analyst Consensus for {ticker}...")

    try:
        stock = yf.Ticker(ticker)

        # 1. GET RECOMMENDATION COUNTS
        recs = stock.recommendations

        if recs is None or recs.empty:
            print("   (No analyst recommendations found)")
            return None

        # Get the latest available period (usually row 0 or index '0m')
        latest = recs.iloc[0]

        # 2. CALCULATE WEIGHTED SCORE (Optimized for Wall St Bias)
        # Analysts rarely sell. We treat "Hold" as a "Soft Sell".

        counts = {
            'strong_buy': latest.get('strongBuy', 0),
            'buy': latest.get('buy', 0),
            'hold': latest.get('hold', 0),
            'sell': latest.get('sell', 0),
            'strong_sell': latest.get('strongSell', 0)
        }

        total_analysts = sum(counts.values())
        if total_analysts == 0: return None

        # SCORING LOGIC:
        # Strong Buy (+2) | Buy (+1)
        # Hold (-0.2) -> Slight penalty because "Hold" often means "Underperform"
        # Sell (-1.5) | Strong Sell (-2.0)

        raw_score = (
            (counts['strong_buy'] * 2.0) +
            (counts['buy'] * 1.0) +
            (counts['hold'] * -0.2) +
            (counts['sell'] * -1.5) +
            (counts['strong_sell'] * -2.0)
        )

        # Normalize to range -1.0 to 1.0
        # Max theoretical score is total * 2
        normalized_score = raw_score / (total_analysts * 2)

        # 3. GET PRICE TARGET UPSIDE
        info = stock.info
        current = info.get('currentPrice') or info.get('regularMarketPrice')
        target = info.get('targetMeanPrice')

        upside_msg = ""
        if current and target:
            upside_pct = ((target - current) / current) * 100
            upside_msg = f" | Avg Target: {target} ({upside_pct:+.1f}%)"

        # 4. CONVERT TO PROBABILITIES [Buy, Hold, Sell]
        # We start with a conservative distribution (Heavy on Hold)
        p_buy, p_hold, p_sell = 0.2, 0.6, 0.2

        if normalized_score > 0.2: # Bullish Threshold
            # Shift from Hold -> Buy
            shift = (normalized_score - 0.2) * 0.8
            p_buy += shift
            p_hold -= shift
        elif normalized_score < 0: # Bearish Threshold
            # Shift from Hold -> Sell
            shift = abs(normalized_score) * 0.8
            p_sell += shift
            p_hold -= shift

        # Safety Clipping
        preds = [max(0.01, p) for p in [p_buy, p_hold, p_sell]]

        # Re-normalize to sum to 1.0
        total_p = sum(preds)
        preds = [round(p/total_p, 2) for p in preds]

        return {
            "model": "Expert_Insight", # Matches the name used in your Report Writer
            "prediction": preds,
            "confidence": min(1.0, total_analysts / 30.0), # More analysts = higher confidence
            "reason": f"Consensus of {int(total_analysts)} Analysts: Score {normalized_score:.2f}{upside_msg}"
        }

    except Exception as e:
        print(f"   (Analyst module error: {e})")
        return None

