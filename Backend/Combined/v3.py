class VeridianTeacher:
    def __init__(self):
        self.labels = ["Buy", "Sell", "Hold"]
        # 👇 UPDATED PATH: Matches your screenshot
        self.model_path = '/content/drive/MyDrive/Veridian/Teacher/veridian_teacher_rf.pkl'
        self.model = None
        self.load_brain()

    def load_brain(self):
        try:
            self.model = joblib.load(self.model_path)
            print("🎓 Teacher AI Loaded (Meta-Learner).")
        except Exception as e:
            print(f"⚠️ Teacher AI not found ({e}). using Smart Weighted Logic.")

    def process(self, student_outputs):
        # 1. PARSE INPUTS
        # (We keep the feature extraction logic in case you retrain the random forest later)
        features = np.zeros((1, 18)) # Expanded for potential future inputs
        model_map = {"Fundamental": 0, "Sentiment": 1, "Alt_Data": 2, "Macro": 3, "Market_Cycle": 4, "Expert_Insight": 5}

        found_models = []
        for s in student_outputs:
            name = s.get('model', 'Unknown')
            if name in model_map:
                found_models.append(name)

        # 2. DECISION LOGIC
        # We use the "Smart Weighted Average" because it is more robust than a missing RF model.

        # --- WEIGHT CONFIGURATION (The "Strategy") ---
        weights = {
            "Fundamental": 0.30,      # The Anchor (30%)
            "Sentiment": 0.20,        # The Momentum (20%)
            "Alt_Data": 0.15,         # The Retail Edge (15%)
            "Market_Cycle": 0.15,     # The Trend (15%)
            "Macro": 0.10,            # The Environment (10%)
            "Expert_Insight": 0.10    # The Sanity Check (10%)
        }

        weighted_probs = np.zeros(3) # [Buy, Hold, Sell]
        total_weight = 0.0

        for s in student_outputs:
            name = s.get('model', 'Unknown')
            w = weights.get(name, 0.0) # Skip unknown models

            # Get prediction vector (Ensure it's a numpy array)
            preds = np.array(s['prediction'])

            # Add to weighted sum
            weighted_probs += preds * w
            total_weight += w

        # Normalize to get final probabilities
        if total_weight > 0:
            final_probs = weighted_probs / total_weight
        else:
            final_probs = np.array([0.33, 0.33, 0.33]) # Fallback if everything fails

        # 3. DETERMINE WINNER
        idx = np.argmax(final_probs)
        decision = self.labels[idx] # Buy, Sell, or Hold

        # Identify the "Loudest" Student for the explanation
        best_student = max(student_outputs, key=lambda x: x['confidence'])

        return {
            "decision": decision,
            "final_probs": final_probs,
            "winner_model": best_student['model'], # Used for visualization focus
            "winner_reason": best_student['reason'],
            "winner_confidence": best_student['confidence'],
            "meta_comment": f"Weighted Strategy (Fund: 30%, Sent: 20%, etc.) based on {len(found_models)} models."
        }

